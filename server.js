const express = require('express');
const cors = require('cors');
const { Connection, PublicKey } = require('@solana/web3.js');

const app = express();
app.use(cors());
app.use(express.json());

// --- CONFIGURATION ---
const USDC_MINT = new PublicKey('EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v'); // Mainnet USDC
const SOLANA_RPC = process.env.SOLANA_RPC || 'https://api.mainnet-beta.solana.com';
const connection = new Connection(SOLANA_RPC, 'confirmed');

// In-memory store for demo purposes. 
// Maps userId -> { expectedAmount, walletAddress, totalReceived, paid }
const userOrders = {};

/**
 * Endpoint: Create or update an order intent
 * Receives the unique address generated by the client
 */
app.post('/api/intent', (req, res) => {
  const { userId, expectedAmount, walletAddress } = req.body;
  
  if (!userId || !expectedAmount || !walletAddress) {
    return res.status(400).json({ error: 'Missing required fields' });
  }

  userOrders[userId] = {
    expectedAmount: parseFloat(expectedAmount),
    walletAddress: walletAddress,
    totalReceived: 0,
    paid: false
  };
  
  console.log(`[Order Created] User: ${userId}, Address: ${walletAddress}, Expected: $${expectedAmount} USDC`);
  
  res.json({ 
    status: 'Intent created', 
    expectedAmount: userOrders[userId].expectedAmount,
    walletAddress: userOrders[userId].walletAddress
  });
});

/**
 * Endpoint: Check payment status
 */
app.get('/api/check-payment/:userId', async (req, res) => {
  const { userId } = req.params;
  const order = userOrders[userId];

  if (!order) {
    return res.status(404).json({ error: 'Order not found' });
  }

  // If already paid, return immediately
  if (order.paid) {
    return res.json({ paid: true, received: order.totalReceived, expected: order.expectedAmount });
  }

  // Check the blockchain for this specific address
  try {
    const walletPubkey = new PublicKey(order.walletAddress);
    
    // Check USDC balance
    let usdcBalance = 0;
    try {
      const tokenAccounts = await connection.getParsedTokenAccountsByOwner(walletPubkey, {
        mint: USDC_MINT
      });
      if (tokenAccounts.value.length > 0) {
        usdcBalance = tokenAccounts.value[0].account.data.parsed.info.tokenAmount.uiAmount;
      }
    } catch (e) {
      // No token account yet
    }

    // If they sent enough (or more, treating extra as tip)
    if (usdcBalance >= order.expectedAmount) {
      order.paid = true;
      order.totalReceived = usdcBalance;
      console.log(`[Payment Confirmed] User: ${userId}, Address: ${order.walletAddress}, Amount: ${usdcBalance} USDC`);
      
      // NOTE: In production, you would now use a server-side key to sweep the funds
      // to your master wallet. Since the private key is stored in the browser's localStorage,
      // the backend cannot sweep it directly without a secure endpoint to retrieve the key.
      
      return res.json({ 
        paid: true, 
        received: usdcBalance, 
        expected: order.expectedAmount 
      });
    } else {
      return res.json({ 
        paid: false, 
        received: usdcBalance, 
        expected: order.expectedAmount 
      });
    }
  } catch (error) {
    console.error("Blockchain check error:", error);
    return res.status(500).json({ error: 'Failed to check blockchain' });
  }
});

const PORT = process.env.PORT || 3000;
app.listen(PORT, () => console.log(`Server running on port ${PORT}`));
